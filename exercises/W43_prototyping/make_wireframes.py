def t(x, y, s, size=14, weight="normal", fill=INK, anchor="start", italic=False):
    st = ' font-style="italic"' if italic else ""
    return (f'<text x="{x}" y="{y}" font-size="{size}" font-weight="{weight}" fill="{fill}" '
            f'text-anchor="{anchor}"{st}>{escape(s)}</text>')


def wrap(s, n):
    lines, cur = [], ""
    for w in s.split():
        if len(cur) + len(w) + 1 > n and cur:
            lines.append(cur)
            cur = w
        else:
            cur = f"{cur} {w}".strip()
    return lines + [cur] if cur else lines


def para(x, y, s, n, size=14, lh=19, **kw):
    out = []
    for i, line in enumerate(wrap(s, n)):
        out.append(t(x, y + i * lh, line, size, **kw))
    return "\n".join(out), y + len(wrap(s, n)) * lh


def box(x, y, w, h, fill=FILL, stroke=LINE, r=6, dash=False):
    d = ' stroke-dasharray="6 5"' if dash else ""
    return f'<rect x="{x}" y="{y}" width="{w}" height="{h}" rx="{r}" fill="{fill}" stroke="{stroke}" stroke-width="1.5"{d}/>'


def label_box(x, y, w, h, s, size=13, fill=FILL, dash=False, n=None):
    body, _ = para(x + 8, y + 18, s, n or max(8, int(w / 7.4)), size, lh=size + 4)
    return box(x, y, w, h, fill, dash=dash) + body


def arrow(*pts):
    """Arrow along a polyline: arrow(x1, y1, x2, y2, ...)."""
    xy = " ".join(f"{pts[i]},{pts[i + 1]}" for i in range(0, len(pts), 2))
    return (f'<polyline points="{xy}" fill="none" stroke="{INK2}" stroke-width="2" '
            f'marker-end="url(#ah)"/>')


def dots(x, y, w, h, groups, r=2.6, step=7):
    """A field of dots, one per ~1 in 1,000, grouped left→right. groups = [(count, fill)]."""
    out, cols = [], max(1, int(w / step))
    i = 0
    for count, fill in groups:
        for _ in range(count):
            cx, cy = x + (i % cols) * step + r, y + (i // cols) * step + r
            assert cy < y + h, "dot field too small: some of the 1,000 dots would be cut off"
            out.append(f'<circle class="d" cx="{cx}" cy="{cy}" r="{r}" fill="{fill}"/>')
            i += 1
    return "\n".join(out)


def phone(x, y, w=210, h=340):
    return (box(x, y, w, h, PAPER, INK2, 18) +
            f'<rect x="{x + w / 2 - 22}" y="{y + 8}" width="44" height="5" rx="2.5" fill="{LINE}"/>')


def svg(title, sub, frames, extra="", height=None):
    h = height or TOP + 2 * CELL_H + RG + 100
    parts = [f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {W} {h}" width="{W}" height="{h}" '
             f'font-family="Segoe UI, Arial, sans-serif">',
             '<defs><marker id="ah" viewBox="0 0 10 10" refX="9" refY="5" markerWidth="7" markerHeight="7" '
             f'orient="auto-start-reverse"><path d="M0,0 L10,5 L0,10 z" fill="{INK2}"/></marker></defs>',
             f'<rect width="{W}" height="{h}" fill="#fff"/>',
             f'<rect x="0" y="0" width="{W}" height="44" fill="#d9d9d9"/>',
             t(M, 29, "DIGITAL WIREFRAME — reference for hand sketch (not the milestone sketch itself)", 17, "bold"),
             t(W - M, 29, "W43 · Americans on AI", 14, fill=INK2, anchor="end"),
             t(M, 80, title, 24, "bold"),
             t(M, 105, sub, 14, fill=INK2)]
    for i, (name, lead, body, data, draw) in enumerate(frames):
        col, row = i % 3, i // 3
        x, y = M + col * (CELL_W + GAP), TOP + row * (CELL_H + RG)
        parts.append(box(x, y, CELL_W, CELL_H, "#fff", LINE, 8))
        parts.append(box(x + 10, y + 10, CELL_W - 20, SKETCH_H, PAPER, LINE, 4))
        parts.append(draw(x + 10, y + 10, CELL_W - 20, SKETCH_H))
        cy = y + SKETCH_H + 38
        parts.append(t(x + 14, cy, name, 16, "bold"))
        parts.append(t(x + CELL_W - 14, cy, "leads: " + lead, 13, fill=INK2, anchor="end"))
        p, cy = para(x + 14, cy + 22, body, 70, 13.5, 18)
        parts.append(p)
        p, _ = para(x + 14, cy + 4, "Data: " + data, 76, 12, 16, fill=INK2, italic=True)
        parts.append(p)
    foot = (f"All numbers: {D.wave_label()} · weighted % · pilot wave excluded · "
            f"source exercises/W39_data/survey_all_waves_all_subgroups.csv · generated by make_wireframes.py")
    parts.append(t(M, h - 22, foot, 12, fill=INK2))
    parts.append(extra)
    parts.append("</svg>")
    return "\n".join(parts)


