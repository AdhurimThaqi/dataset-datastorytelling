def fetch(name, width=1600):
    url = "https://commons.wikimedia.org/wiki/Special:FilePath/" + urllib.parse.quote(name) + f"?width={width}"
    for attempt in range(6):            # Commons answers 429 when asked too fast: wait and retry
        try:
            time.sleep(2)
            with urllib.request.urlopen(urllib.request.Request(url, headers=UA), timeout=60) as r:
                return Image.open(io.BytesIO(r.read()))
        except urllib.error.HTTPError as e:
            if e.code != 429: raise
            time.sleep(10 * (attempt + 1))
    raise RuntimeError("Commons keeps saying 429 for " + name)


def save(im, path):
    im = im.convert("RGB")
    w, h = im.size
    if w / h > 4 / 3:   # centre crop to 4:3
        nw = int(h * 4 / 3); im = im.crop(((w - nw) // 2, 0, (w - nw) // 2 + nw, h))
    else:
        nh = int(w * 3 / 4); im = im.crop((0, (h - nh) // 2, w, (h - nh) // 2 + nh))
    im.resize((1200, 900), Image.LANCZOS).save(path, "JPEG", quality=80, optimize=True, progressive=True)


